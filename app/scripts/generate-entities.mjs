#!/usr/bin/env node
// Generate Rayfin connector entity files for the evaluation tables from the metadata.json that
// `npx rayfin connector add --type fabric-sqlanalytics ...` discovered. Follows the Rayfin
// "Generating entity files" contract: one keyless, read-only entity per table plus schema.ts.
//
//   node scripts/generate-entities.mjs --project <your Rayfin app> [--connector evals]
//   node scripts/generate-entities.mjs --metadata <metadata.json> --out <folder>   (any location)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COLUMNS } from '../overlay/src/eval/generated/contract.ts';

export const APP_TABLES = ['EvalRun', 'EvalQuestion', 'EvalResult', 'FabricIqQuery', 'EvalEvent'];
const RESERVED = new Set(['Query', 'Mutation', 'Subscription', 'Date', 'DateTime', 'Decimal', 'String', 'Int', 'Float', 'Boolean', 'ID', 'UUID', 'URL']);
const DECORATOR_ORDER = ['boolean', 'date', 'decimal', 'int', 'text', 'uuid'];
const TYPE_FAMILIES = [
  [['int', 'bigint', 'smallint', 'tinyint'], 'int', 'number'],
  [['decimal', 'numeric', 'money', 'smallmoney', 'float', 'real'], 'decimal', 'number'],
  [['bit'], 'boolean', 'boolean'],
  [['date', 'datetime', 'datetime2', 'smalldatetime', 'datetimeoffset', 'time'], 'date', 'Date'],
  [['uniqueidentifier'], 'uuid', 'string'],
  [['varchar', 'nvarchar', 'char', 'nchar', 'text', 'ntext'], 'text', 'string'],
];

export function words(name) {
  return String(name).match(/[A-Z]+(?![a-z])|[A-Z]?[a-z]+|\d+/g) ?? [];
}

export function camelCase(name) {
  return words(name).map((w, i) => {
    const lower = w.toLowerCase();
    return i === 0 ? lower : lower.charAt(0).toUpperCase() + lower.slice(1);
  }).join('');
}

export function pascalCase(name) {
  const c = camelCase(name);
  return c.charAt(0).toUpperCase() + c.slice(1);
}

function mapType(dataType) {
  const t = String(dataType).toLowerCase();
  for (const [names, decorator, tsType] of TYPE_FAMILIES) if (names.includes(t)) return { decorator, tsType, known: true };
  return { decorator: 'text', tsType: 'string', known: false };
}

function quote(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

export function entityFile(table, warnings) {
  const className = RESERVED.has(pascalCase(table.tableName)) ? `${pascalCase(table.tableName)}Record` : pascalCase(table.tableName);
  if (className !== pascalCase(table.tableName)) warnings.push(`Renamed reserved entity ${table.tableName} to ${className}.`);
  const used = new Set();
  const fields = [];
  for (const col of table.columns) {
    const prop = camelCase(col.columnName);
    const { decorator, tsType, known } = mapType(col.dataType);
    if (!known) warnings.push(`Unknown SQL type ${col.dataType} for ${table.tableName}.${col.columnName}; falling back to @text().`);
    used.add(decorator);
    const opts = [];
    if (col.isNullable) opts.push('optional: true');
    if (prop !== col.columnName) opts.push(`column: ${quote(col.columnName)}`);
    if (decorator === 'text' && col.maxLength > 0) opts.push(`max: ${col.maxLength}`);
    if (decorator === 'decimal' && col.precision != null && col.scale != null) opts.push(`precision: ${col.precision}`, `scale: ${col.scale}`);
    const type = tsType === 'Date' && className === 'Date' ? 'globalThis.Date' : tsType;
    fields.push(`  @${decorator}(${opts.length ? `{ ${opts.join(', ')} }` : ''}) ${prop}${col.isNullable ? '?' : '!'}: ${type};`);
  }
  const keys = (table.primaryKeyColumns ?? []).map((k) => quote(camelCase(k)));
  if (!keys.length) warnings.push(`No PK metadata available for ${table.tableName}; generated as a keyless entity.`);
  const decorators = ['entity', ...DECORATOR_ORDER.filter((d) => used.has(d))];
  const text = [
    '// Generated by scripts/generate-entities.mjs from metadata.json. Re-run after the source schema changes.',
    "import { role } from '@microsoft/rayfin-core';",
    `import { ${decorators.join(', ')} } from '@microsoft/rayfin-core';`,
    "import { Source } from '@microsoft/rayfin-connectors';",
    '',
    "@role('authenticated', ['read'])",
    '@entity()',
    `export class ${className} extends Source({ schema: ${quote(table.schemaName ?? 'dbo')}, table: ${quote(table.tableName)}, primaryKey: [${keys.join(', ')}] }) {`,
    ...fields,
    '}',
    '',
  ].join('\n');
  return { className, text, fields: table.columns.map((c) => camelCase(c.columnName)) };
}

export function schemaFile(connector, entities) {
  const typeName = `${pascalCase(connector)}Schema`;
  const lines = [
    '// Generated by scripts/generate-entities.mjs from metadata.json. Re-run after the source schema changes.',
    "import type { GraphQLBackedConnector } from '@microsoft/rayfin-connector-fabric-graphql';",
    "import type { ConnectorConfig } from '@microsoft/rayfin-connectors';",
    '',
    ...entities.map((e) => `import type { ${e.className} } from './${e.className}.js';`),
    '',
    ...entities.map((e) => `export type { ${e.className} } from './${e.className}.js';`),
    '',
    'export const connectorConfig = {',
    "  connector: 'fabric-sqlanalytics',",
    "  operations: ['read'],",
    '  entities: {',
    ...entities.map((e) => `    ${e.className}: [${e.fields.map(quote).join(', ')}],`),
    '  },',
    '} as const satisfies ConnectorConfig;',
    '',
    `export type ${typeName} = GraphQLBackedConnector<`,
    `  { ${entities.map((e) => `${e.className}: typeof ${e.className}`).join('; ')} },`,
    '  typeof connectorConfig',
    '>;',
    '',
  ];
  return lines.join('\n');
}

/** Read and validate everything before any output directory/file is changed. */
export function prepareGeneration({ project, connector = 'evals', tables = APP_TABLES, metadata, out }) {
  const dir = out ?? join(project, 'rayfin', 'connectors', connector);
  const metaPath = metadata ?? join(dir, 'metadata.json');
  if (!existsSync(metaPath)) throw new Error(`${metaPath} not found. Run 'npx rayfin connector add --type fabric-sqlanalytics ... --name ${connector}' first.`);
  const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
  const found = new Map();
  for (const schema of meta.schemas ?? []) {
    for (const t of schema.tables ?? []) {
      if (tables.includes(t.tableName) && found.has(t.tableName)) throw new Error(`Ambiguous table ${t.tableName} in metadata.json: select one source schema before applying the scorecard.`);
      found.set(t.tableName, { ...t, schemaName: schema.schemaName });
    }
  }
  const warnings = [];
  const missing = tables.filter((t) => !found.has(t));
  if (missing.length) {
    throw new Error(`metadata.json has no table(s) ${missing.join(', ')}. Create the lakehouse shortcuts (python -m cfeval shortcuts ...), then refresh the connector metadata.`);
  }
  for (const name of tables) {
    const table = found.get(name);
    if (!Array.isArray(table.columns)) throw new Error(`No column metadata for ${name}. Refresh connector discovery first.`);
    const columns = new Map(table.columns.map((c) => [c.columnName, c]));
    for (const [prop, [column, type]] of Object.entries(COLUMNS[name] ?? {})) {
      const col = columns.get(column);
      if (!col) throw new Error(`metadata.json is missing required column ${name}.${column}. Refresh the source/connector schema before applying the overlay.`);
      const mapped = mapType(col.dataType);
      const expected = type === 'datetime' ? 'Date' : type === 'int' || type === 'real' ? 'number' : 'string';
      if (!mapped.known || mapped.tsType !== expected || camelCase(col.columnName) !== prop) {
        throw new Error(`Incompatible column mapping for ${name}.${column}: ${col.dataType}; expected app ${type} field ${prop}.`);
      }
    }
  }
  const entities = tables.map((t) => entityFile(found.get(t), warnings));
  return { dir, entities, warnings, schema: schemaFile(connector, entities) };
}

export function writeGeneration({ dir, entities, warnings, schema }, log = console.log) {
  mkdirSync(dir, { recursive: true });
  for (const e of entities) writeFileSync(join(dir, `${e.className}.ts`), e.text);
  writeFileSync(join(dir, 'schema.ts'), schema);
  log(`Generated ${entities.length} entities and schema.ts in ${dir}`);
  for (const w of warnings) log(`  note: ${w}`);
  return { entities, warnings };
}

export function generate({ log = console.log, ...options }) {
  return writeGeneration(prepareGeneration(options), log);
}

function args(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i].startsWith('--')) out[argv[i].slice(2)] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const a = args(process.argv.slice(2));
  try {
    generate({
      project: a.project ?? process.cwd(), connector: a.connector ?? 'evals', metadata: a.metadata, out: a.out,
      tables: a.tables ? String(a.tables).split(',') : APP_TABLES,
    });
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
