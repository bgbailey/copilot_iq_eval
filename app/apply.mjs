#!/usr/bin/env node
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
if (args.length !== 2 || args[0] !== '--project') {
  console.error('Usage: node app/apply.mjs --project <Rayfin project>');
  process.exit(1);
}
const project = resolve(args[1]);
const frontend = join(project, 'packages/frontend/src');
const connector = join(project, 'rayfin/connectors/evals');
const metadataPath = join(connector, 'metadata.json');
const rootPath = join(frontend, 'Root.tsx');
const appPath = join(frontend, 'App.tsx');
const clientPath = join(frontend, 'lib/rayfin-client.ts');
const fail = message => { throw new Error(message); };
if (!existsSync(rootPath) || !existsSync(appPath) || !existsSync(clientPath)) fail('Expected a Rayfin 2.x blankapp project with packages/frontend/src.');
if (!existsSync(metadataPath)) fail('Add the evals fabric-sqlanalytics connector first; metadata.json is missing.');
const metadata = JSON.parse(readFileSync(metadataPath, 'utf8'));
const required = {
  EvalRuns: ['RunId', 'Label', 'StartedUtc', 'Mode', 'TestUser', 'Questions', 'Answers', 'Passed', 'PassRate'],
  EvalResults: ['RunId', 'QuestionId', 'Attempt', 'AskedUtc', 'Question', 'Answer', 'Expected', 'Found', 'ValueCheck', 'ValueReason', 'CitedReports', 'CitationCheck', 'CitationReason', 'QueriedModels', 'ModelCheck', 'ModelReason', 'Verdict', 'LatencyMs'],
  EvalQueries: ['RunId', 'QuestionId', 'Attempt', 'Timestamp', 'SemanticModel', 'Dax', 'DurationMs'],
};
const prop = name => name[0].toLowerCase() + name.slice(1);
const files = {};
for (const [name, columns] of Object.entries(required)) {
  const matches = (metadata.schemas || []).flatMap(schema => (schema.tables || []).filter(t => t.tableName === name).map(table => ({ schema, table })));
  if (matches.length !== 1) fail(`Expected exactly one ${name} table in connector metadata; found ${matches.length}.`);
  const { schema, table } = matches[0];
  for (const column of columns) if (!table.columns.some(c => c.columnName === column)) fail(`${name} is missing ${column}.`);
  const keys = table.primaryKeyColumns || [];
  for (const key of keys) {
    const column = table.columns.find(c => c.columnName === key);
    if (!column || column.isNullable) fail(`Invalid primary key ${name}.${key}.`);
  }
  const kinds = new Set();
  const fields = columns.map(name => {
    const c = table.columns.find(column => column.columnName === name);
    const type = c.dataType.toLowerCase();
    const kind = /^(int|bigint|smallint|tinyint)$/.test(type) ? 'int'
      : /^(decimal|numeric|money|smallmoney|float|real)$/.test(type) ? 'decimal'
      : /^(date|datetime|datetime2|smalldatetime|datetimeoffset|time)$/.test(type) ? 'date'
      : /^(varchar|nvarchar|char|nchar|text|ntext)$/.test(type) ? 'text' : null;
    if (!kind) fail(`Unsupported SQL type ${c.dataType} for ${table.tableName}.${name}.`);
    kinds.add(kind);
    const options = { ...(c.isNullable ? { optional: true } : {}), column: name };
    if (kind === 'decimal' && c.precision != null && c.scale != null) Object.assign(options, { precision: c.precision, scale: c.scale });
    const ts = kind === 'date' ? 'Date' : kind === 'text' ? 'string' : 'number';
    return `  @${kind}(${JSON.stringify(options)}) ${prop(name)}${c.isNullable ? '?' : '!'}: ${ts};`;
  });
  files[`${name}.ts`] = `// Generated by the scorecard overlay.\nimport { entity, role, ${[...kinds].join(', ')} } from '@microsoft/rayfin-core';\nimport { Source } from '@microsoft/rayfin-connectors';\n\n@role('authenticated', ['read'])\n@entity()\nexport class ${name} extends Source(${JSON.stringify({ schema: schema.schemaName, table: name, primaryKey: keys.map(prop) })}) {\n${fields.join('\n')}\n}\n`;
}
files['schema.ts'] = `// Generated by the scorecard overlay.
import type { GraphQLBackedConnector } from '@microsoft/rayfin-connector-fabric-graphql';
import type { ConnectorConfig } from '@microsoft/rayfin-connectors';
${Object.keys(required).map(n => `import { ${n} } from './${n}.js';`).join('\n')}
export const connectorConfig = { connector: 'fabric-sqlanalytics', operations: ['read'], entities: { ${Object.keys(required).join(', ')} } } as const satisfies ConnectorConfig;
export type EvalsSchema = GraphQLBackedConnector<{ ${Object.keys(required).map(n => `${n}: typeof ${n}`).join('; ')} }, typeof connectorConfig>;
`;
for (const [name, content] of Object.entries(files)) {
  const path = join(connector, name);
  if (existsSync(path) && name !== 'schema.ts' && !readFileSync(path, 'utf8').startsWith('// Generated by the scorecard overlay.')) fail(`Refusing to overwrite ${path}.`);
  if (name === 'schema.ts' && existsSync(path)) {
    const old = readFileSync(path, 'utf8');
    if (!old.startsWith('// Generated by the scorecard overlay.') && !/placeholder|TODO/i.test(old)) fail(`Refusing to overwrite existing ${path}; move it aside first.`);
  }
}
let root = readFileSync(rootPath, 'utf8');
if (root.includes('<AuthGate>') && root.includes('</AuthGate>')) {
  root = root.replace(/import \{ AuthGate \} from ['"].*?['"];\s*/, '').replace('<AuthGate>', '').replace('</AuthGate>', '');
} else if (root.includes('AuthGate')) fail('Unrecognized AuthGate in Root.tsx; cannot safely apply.');
let client = readFileSync(clientPath, 'utf8');
const marker = '// Scorecard connector registration';
if (!client.includes(marker)) {
  const services = 'services: { data: dataService<UniversalAppSchema>() }';
  if (!client.includes(services)) fail('Unrecognized Rayfin client services; cannot safely wire the evals connector.');
  client = client.replace(services, 'services: { data: dataService<UniversalAppSchema>(), connectors: connectorsService<{ evals: EvalsSchema }>({ configs: { evals: connectorConfig } }) }');
  client = `${marker}\nimport { connectorsService } from '@microsoft/rayfin-connectors';\nimport { connectorConfig, type EvalsSchema } from '../../../../rayfin/connectors/evals/schema';\n${client}`;
}
for (const [name, content] of Object.entries(files)) writeFileSync(join(connector, name), content);
mkdirSync(join(frontend, 'eval'), { recursive: true });
for (const name of ['EvalApp.tsx', 'data.ts', 'sample-data.json', 'eval.css']) copyFileSync(join(here, 'src/eval', name), join(frontend, 'eval', name));
writeFileSync(rootPath, root);
writeFileSync(clientPath, client);
writeFileSync(appPath, "export { default } from './eval/EvalApp';\n");
console.log('Scorecard applied. Run the connector install command printed by rayfin connector add, then build and deploy.');
